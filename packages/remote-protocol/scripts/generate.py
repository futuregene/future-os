#!/usr/bin/env python3
"""Generate Remote command bindings from command.schema.json; never run tests."""

import argparse
import json
from pathlib import Path
import re
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]


def rust_default(value, rust_type):
    if rust_type == "String":
        return "String::new()" if value == "" else f"{json.dumps(value)}.into()"
    if rust_type.startswith("Vec<"):
        assert value == []
        return "Vec::new()"
    if rust_type.startswith("Option<"):
        assert value is None
        return "None"
    if rust_type == "serde_json::Value":
        assert value is None
        return "serde_json::Value::Null"
    return json.dumps(value)


def generate():
    schema = json.loads((ROOT / "command.schema.json").read_text())
    assert schema["x-version"] == 1
    fields = schema["properties"]
    rust = [
        "// Generated by scripts/generate.py from command.schema.json. Do not edit.",
        "use serde::{Deserialize, Serialize};",
        "#[derive(Debug, Deserialize, Serialize)]",
        '#[serde(rename_all = "camelCase", default)]',
        "pub struct IncomingCmd {",
    ]
    for wire, field in fields.items():
        if field.get("description"):
            rust.append("    /// " + field["description"])
        if wire == "type":
            rust.append('    #[serde(rename = "type")]')
        rust.append(f'    pub {field["x-rust-name"]}: {field["x-rust-type"]},')
    rust += ["}", "impl Default for IncomingCmd {", "    fn default() -> Self {", "        Self {"]
    for field in fields.values():
        value = rust_default(field["default"], field["x-rust-type"])
        rust.append(f'            {field["x-rust-name"]}: {value},')
    rust += ["        }", "    }", "}"]
    for name, definition in schema["$defs"].items():
        rust += [
            "#[derive(Debug, Clone, Serialize, Deserialize)]",
            '#[serde(rename_all = "camelCase")]',
            f"pub struct {name} {{",
        ]
        for wire, field in definition["properties"].items():
            # Current definitions contain required strings only. Fail closed
            # when the schema needs a new mapping, rather than emitting drift.
            assert field["type"] == "string" and wire in definition["required"]
            rust_name = re.sub(r"[A-Z]", lambda m: "_" + m[0].lower(), wire)
            rust.append(f"    pub {rust_name}: String,")
        rust.append("}")
    formatted = subprocess.check_output(
        ["rustfmt", "--edition", "2021", "--emit", "stdout"],
        input=("\n".join(rust) + "\n").encode(),
    ).decode()
    ts = [
        "// Generated by scripts/generate.py from command.schema.json. Do not edit.",
        'import type { BuiltinProviderUpdate, CustomProviderUpsert, DesktopSettings } from "./types";',
        "", "export interface RemoteCommand {",
    ]
    for wire, field in fields.items():
        optional = "" if wire in schema["required"] else "?"
        if field.get("description"):
            ts.append("  /** " + field["description"] + " */")
        ts.append(f'  {wire}{optional}: {field["x-ts-type"]};')
    ts += ["}", ""]
    for name, definition in schema["$defs"].items():
        ts.append(f"export interface {name} {{")
        for wire in definition["properties"]:
            ts.append(f"  {wire}: string;")
        ts += ["}", ""]
    return {"src/command_generated.rs": formatted, "src/command.generated.ts": "\n".join(ts)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for name, source in generate().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != source:
                stale.append(name)
        else:
            path.write_text(source)
    if stale:
        print("Stale Remote bindings: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
