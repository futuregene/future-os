"""Generate C3 projections with the real Rust path, chained sticky per chain.

C3 is the runtime default: C's projection plus a sticky model-written handoff summary.
`agent/examples/abc_c3_probe.rs` calls the production entry point
(`prepare_evidence_with_summary`), so the projection content is exactly what production
would commit, and the summary is generated by a real model call.

Chaining mirrors production: each stage's checkpoint is handed to the next compaction,
so the summary accumulates instead of being rewritten from scratch.

Input: frozen real sessions (see `freeze_sessions.py`) and the synthetic fixtures.
Output: `<root>/C3proj/projections/<identity>.json`, plus a ledger of the summary
requests (tokens, cache counters, cost) for the report.
"""
import argparse, json, pathlib, subprocess, sys, time

WT = pathlib.Path("/Users/geilige/future-os/.worktrees/session-history-a47313")
ROOT = pathlib.Path("/Users/geilige/future-os/.future/research/abc-summary-a47313")
DRIVER = pathlib.Path("/Users/geilige/future-os/target/debug/examples/abc_c3_probe")
SYNTH = (0, 3, 7)
REAL_FRACTIONS = (0.4, 0.7, 1.0)


def boundaries(root):
    """(chain, stage_index, records) for every measured boundary."""
    out = []
    for task in ("export", "analysis", "pipeline"):
        for stage in SYNTH:
            p = root / "data" / f"{task}-{stage}.json"
            if not p.exists():
                continue
            d = json.loads(p.read_text())
            out.append((task, stage, d["archive"] + d["tail"]))
    frozen = root / "frozen-sessions" / "manifest.json"
    if frozen.exists():
        manifest = json.loads(frozen.read_text())
        for name, meta in manifest.items():
            records = json.loads(pathlib.Path(meta["path"]).read_text())["records"]
            # one entry per stage, cumulative
            for index, frac in enumerate(REAL_FRACTIONS):
                out.append((name, index, records[:max(1, int(len(records) * frac))]))
    grouped = {}
    for chain, stage, records in out:
        grouped.setdefault(chain, []).append((stage, records))
    for chain in grouped:
        grouped[chain].sort(key=lambda item: item[0])
    return grouped


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=pathlib.Path, default=ROOT)
    ap.add_argument("--model", default="future/deepseek-flash")
    ap.add_argument("--window", type=int, default=128_000)
    ap.add_argument("--only", nargs="*", default=None)
    ap.add_argument("--no-summary", action="store_true",
                    help="plain C (deterministic only) — for the ablation")
    args = ap.parse_args()

    chains = boundaries(args.root)
    if args.only:
        chains = {k: v for k, v in chains.items() if k in args.only}

    tag = "Cdet" if args.no_summary else "C3proj"
    outdir = args.root / tag / "projections"
    indir = args.root / tag / "input"
    outdir.mkdir(parents=True, exist_ok=True)
    indir.mkdir(parents=True, exist_ok=True)

    ledger_path = args.root / f"{tag}-ledger.json"
    ledger = json.loads(ledger_path.read_text()) if ledger_path.exists() else {}

    for chain, stages in chains.items():
        previous = None
        for stage, records in stages:
            identity = f"{chain}__s{stage}"
            target = outdir / f"{identity}.json"
            if target.exists():
                previous = json.loads(target.read_text()).get("checkpoint")
                print(f"  {identity}: cached", flush=True)
                continue
            records_file = indir / f"{identity}.json"
            records_file.write_text(json.dumps(records, ensure_ascii=False) + "\n")
            argv = [str(DRIVER), "--records", str(records_file), "--model", args.model,
                    "--window", str(args.window)]
            if args.no_summary:
                argv.append("--no-summary")
            elif previous is not None:
                argv += ["--previous", json.dumps(previous)]
            began = time.monotonic()
            run = subprocess.run(argv, capture_output=True, text=True, timeout=2400)
            if run.returncode != 0:
                print(f"  {identity}: DRIVER FAILED {run.stderr[-400:]}", flush=True)
                continue
            payload = json.loads(run.stdout.strip().splitlines()[-1])
            text = "\n\n".join(m["text"] for m in payload["projection"])
            previous = payload["checkpoint"]
            target.write_text(json.dumps({
                "id": identity, "text": text, "chain": chain, "stage": stage,
                "source": f"real C3 ({'no summary' if args.no_summary else 'sticky summary'})",
                "context_tokens": len(text) // 4,
                "estimated_before": payload["estimated_before"],
                "estimated_after": payload["estimated_after"],
                "usage": payload["usage"],
                "wall_seconds": round(time.monotonic() - began, 3),
                "checkpoint": payload["checkpoint"],
                "summary_used": (not args.no_summary) and payload["usage"]["input_tokens"] > 0,
            }, ensure_ascii=False, indent=2) + "\n")
            ledger[identity] = payload["usage"]
            ledger_path.write_text(json.dumps(ledger, indent=2) + "\n")
            u = payload["usage"]
            print(f'  {identity}: {len(text)} chars (~{len(text)//4} tok), '
                  f'{len(payload["projection"])} msgs, requests={payload["model_requests"]}, '
                  f'in={u["input_tokens"]} cache_read={u["cache_read_tokens"]} '
                  f'cost={u["cost"]:.4f}', flush=True)

    spent = sum(v.get("cost", 0.0) for v in ledger.values())
    print(f'\n{tag}: {len(list(outdir.glob("*.json")))} projections, '
          f'summary cost CNY {spent:.4f}')
    print(f'total experiment spend CNY '
          f'{sum(x.get("cost", 0.0) for x in ledger.values()) + 0:.4f} (this tag only)')


if __name__ == "__main__":
    main()
